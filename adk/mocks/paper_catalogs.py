def resolve_offline_catalog(task_id: str | None = None, query: str = "") -> list[dict[str, Any]]:
    """Resolve matching offline catalog based on task_id or query keywords."""
    if task_id and task_id in DOMAIN_CATALOG_MAP:
        return DOMAIN_CATALOG_MAP[task_id]
    q_low = (query or "").lower()
    if "anomaly" in q_low or "biosignal" in q_low or "telemetry" in q_low or "isolation" in q_low:
        return ANOMALY_DETECTION_CATALOG
    if "pathfinding" in q_low or "octile" in q_low or "dijkstra" in q_low or "grid" in q_low:
        return GRAPH_PATHFINDING_CATALOG
