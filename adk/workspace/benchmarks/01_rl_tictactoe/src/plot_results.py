"""Tools for visualizing experiment results."""
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from typing import List, Tuple
from pathlib import Path
default_figures: List[Tuple[str, str]] = [('figures/comparison_chart.pdf', 'comparison_chart.png')]

def plot_comparison_results(results_data: List[dict], output_path: Path, figure_name: str='Comparison') -> None:
    """Plot a comparison chart of win/draw rates against the random baseline.
    Results data should be rows from the CSV generated by run_experiment."""
    import pandas as pd
    import numpy as np
    if not results_data:
        raise ValueError('results_data cannot be empty')
    df = pd.DataFrame(results_data)
    methods = df['method'].unique()
    baseline_methods = ['random']
    if any((m in baseline_methods for m in methods)):
        baseline_data = df[df['method'] == 'random']['value'].values
        ql_data = df[df['method'] != 'random']['value'].values
        q_mean = np.mean(ql_data)
        q_std = np.std(ql_data) if len(ql_data) > 0 else 0.0
        b_mean = np.mean(baseline_data)
        b_std = np.std(baseline_data) if len(baseline_data) > 0 else 0.0
    else:
        q_rates = df[df['method'] == 'q_learning']['value'].values
        r_rates = df[df['method'] == 'random']['value'].values if 'random' in df['method'].values else []
        if not r_rates:
            q_mean = np.mean(q_rates) if len(q_rates) > 0 else 0.0
            q_std = np.std(q_rates) if len(q_rates) > 0 else 0.0
        b_mean = 2 / 9
        b_std = 0.0
    fig, ax = plt.subplots(figsize=(10, 6))
    x_positions = [0]
    y_error_q = [q_std] if q_std > 0 else [0]
    ax.bar(x_positions, q_mean, yerr=y_error_q, color='blue', label=f'Q-Learning (mean: {q_mean:.2f})')
    x_positions_random = [1]
    y_error_r = [b_std] if b_std > 0 else [0]
    ax.bar(x_positions_random, b_mean, yerr=y_error_r, color='gray', label=f'Random Opponent (baseline)')
    ax.set_xticks([0.5])
    ax.set_xticklabels(['Win/Draw vs Random'])
    ax.set_ylabel('Win/Draw Rate')
    ax.legend()
    ax.grid(axis='y', linestyle='--', alpha=0.7)
    plt.tight_layout()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(output_path)
    print(f'Comparison chart saved to {output_path}')
